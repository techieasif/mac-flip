import Foundation

/// 5×7 uppercase dot font. Each row is five bits, high bit on the left.
enum DotFont {
    static let columns = 5
    static let rows = 7

    static func rows(for character: Character) -> [UInt8] {
        glyphs[character] ?? glyphs[" "] ?? Array(repeating: 0, count: 7)
    }

    static func sanitize(_ text: String) -> String {
        let folded = text.folding(options: .diacriticInsensitive, locale: Locale(identifier: "en_US_POSIX")).uppercased()
        return String(folded.map { glyphs[$0] == nil ? " " : $0 })
    }

    private static func g(_ lines: String...) -> [UInt8] {
        var result: [UInt8] = []
        for line in lines.prefix(7) {
            var bits: UInt8 = 0
            for (index, character) in line.prefix(5).enumerated() where character == "1" {
                bits |= 1 << (4 - index)
            }
            result.append(bits)
        }
        while result.count < 7 {
            result.append(0)
        }
        return result
    }

